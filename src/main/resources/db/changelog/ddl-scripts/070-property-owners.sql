CREATE SEQUENCE PROPERTY_OWNER_SEQ START WITH 1 INCREMENT BY 1;

CREATE TABLE PROPERTY_OWNER (
    OWNER_ID BIGINT PRIMARY KEY,
    USER_ACCOUNT_ID BIGINT NOT NULL REFERENCES USER_ACCOUNT (USER_ACCOUNT_ID),
    VERSION BIGINT NOT NULL DEFAULT 0,
    FIRST_NAME VARCHAR(50) NOT NULL,
    LAST_NAME VARCHAR(50) NOT NULL,
    EMAIL VARCHAR(254) NOT NULL,
    STREET_NAME VARCHAR(100),
    BUILDING_NUMBER VARCHAR(10) NOT NULL,
    APARTMENT_NUMBER VARCHAR(10),
    ZIP_CODE VARCHAR(6) NOT NULL,
    CITY_NAME VARCHAR(60) NOT NULL,
    REPRESENTATIVE_NAME VARCHAR(120),
    REPRESENTATIVE_EMAIL VARCHAR(254),
    ACCOUNT_NUMBER VARCHAR(26) NOT NULL,
    PAYMENT_ACCOUNT_HOLDER VARCHAR(20) NOT NULL CHECK (PAYMENT_ACCOUNT_HOLDER IN ('OWNER', 'REPRESENTATIVE')),
    INSERT_DATE TIMESTAMP NOT NULL,
    UPDATE_DATE TIMESTAMP,
    INSERT_OPERATOR VARCHAR(60) NOT NULL,
    UPDATE_OPERATOR VARCHAR(60),
    CONSTRAINT CK_OWNER_REPRESENTATIVE CHECK ((REPRESENTATIVE_NAME IS NULL) = (REPRESENTATIVE_EMAIL IS NULL)),
    CONSTRAINT CK_OWNER_ACCOUNT_HOLDER CHECK (PAYMENT_ACCOUNT_HOLDER <> 'REPRESENTATIVE' OR REPRESENTATIVE_NAME IS NOT NULL)
);
CREATE INDEX I_PROPERTY_OWNER_USER ON PROPERTY_OWNER (USER_ACCOUNT_ID);

ALTER TABLE APARTMENT ADD COLUMN OWNER_ID BIGINT REFERENCES PROPERTY_OWNER (OWNER_ID);
CREATE INDEX I_APARTMENT_OWNER ON APARTMENT (OWNER_ID);
