CREATE TABLE RENTAL_DOCUMENT_COUNTER (
    OWNER_ID BIGINT NOT NULL REFERENCES PROPERTY_OWNER (OWNER_ID),
    DOCUMENT_TYPE VARCHAR(30) NOT NULL,
    DOCUMENT_YEAR INT NOT NULL,
    LAST_NUMBER INT NOT NULL,
    PRIMARY KEY (OWNER_ID, DOCUMENT_TYPE, DOCUMENT_YEAR)
);

CREATE TABLE RENTAL_DOCUMENT (
    DOCUMENT_ID UUID PRIMARY KEY,
    USER_ACCOUNT_ID BIGINT NOT NULL REFERENCES USER_ACCOUNT (USER_ACCOUNT_ID),
    OWNER_ID BIGINT NOT NULL REFERENCES PROPERTY_OWNER (OWNER_ID),
    TENANT_ID BIGINT REFERENCES TENANT (TENANT_ID) ON DELETE SET NULL,
    SETTLEMENT_ID BIGINT REFERENCES SETTLEMENT (SETTLEMENT_ID) ON DELETE SET NULL,
    LEASE_AGREEMENT_ID BIGINT REFERENCES LEASE_AGREEMENT (LEASE_AGREEMENT_ID) ON DELETE SET NULL,
    SOURCE_KEY VARCHAR(80) NOT NULL UNIQUE,
    DOCUMENT_TYPE VARCHAR(30) NOT NULL,
    DOCUMENT_YEAR INT NOT NULL,
    SEQUENCE_NUMBER INT NOT NULL,
    DOCUMENT_NUMBER VARCHAR(30) NOT NULL,
    TEMPLATE_VERSION INT NOT NULL DEFAULT 1,
    SNAPSHOT TEXT NOT NULL,
    PDF_FILE_NAME VARCHAR(80),
    PDF_SHA256 VARCHAR(64),
    CANCELLED BOOLEAN NOT NULL DEFAULT FALSE,
    CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT UK_RENTAL_DOCUMENT_NUMBER UNIQUE (OWNER_ID, DOCUMENT_TYPE, DOCUMENT_YEAR, SEQUENCE_NUMBER)
);
CREATE INDEX I_RENTAL_DOCUMENT_USER ON RENTAL_DOCUMENT (USER_ACCOUNT_ID, CREATED_AT);
CREATE INDEX I_RENTAL_DOCUMENT_TENANT ON RENTAL_DOCUMENT (TENANT_ID);
CREATE INDEX I_RENTAL_DOCUMENT_SETTLEMENT ON RENTAL_DOCUMENT (SETTLEMENT_ID);

CREATE TABLE DOCUMENT_DELIVERY (
    DELIVERY_ID UUID PRIMARY KEY,
    DOCUMENT_ID UUID NOT NULL REFERENCES RENTAL_DOCUMENT (DOCUMENT_ID),
    KIND VARCHAR(20) NOT NULL CHECK (KIND IN ('ISSUE', 'CANCELLATION')),
    TO_ADDRESS VARCHAR(254) NOT NULL,
    CC_JSON TEXT NOT NULL,
    SEND_ENABLED BOOLEAN NOT NULL,
    STATE VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    ATTEMPT_COUNT INT NOT NULL DEFAULT 0,
    NEXT_ATTEMPT_AT TIMESTAMPTZ NOT NULL DEFAULT now(),
    LEASE_UNTIL TIMESTAMPTZ,
    LEASE_TOKEN UUID,
    SMTP_STARTED_AT TIMESTAMPTZ,
    LAST_ERROR VARCHAR(1000),
    CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT now(),
    FINISHED_AT TIMESTAMPTZ,
    CONSTRAINT UK_DOCUMENT_DELIVERY_KIND UNIQUE (DOCUMENT_ID, KIND)
);
CREATE INDEX I_DOCUMENT_DELIVERY_PENDING ON DOCUMENT_DELIVERY (STATE, NEXT_ATTEMPT_AT);

CREATE TABLE DOCUMENT_DELIVERY_ATTEMPT (
    ATTEMPT_ID UUID PRIMARY KEY,
    DELIVERY_ID UUID NOT NULL REFERENCES DOCUMENT_DELIVERY (DELIVERY_ID),
    ATTEMPT_NUMBER INT NOT NULL,
    STARTED_AT TIMESTAMPTZ NOT NULL DEFAULT now(),
    FINISHED_AT TIMESTAMPTZ,
    OUTCOME VARCHAR(20) NOT NULL,
    ERROR_MESSAGE VARCHAR(1000),
    CONSTRAINT UK_DOCUMENT_DELIVERY_ATTEMPT UNIQUE (DELIVERY_ID, ATTEMPT_NUMBER)
);

