CREATE SEQUENCE RENTAL_PAYMENT_SEQ START WITH 1 INCREMENT BY 1;

-- Real receipts belong to a tenancy, never to a monthly settlement.
-- Deleted receipts retain their request ID so a delayed retry cannot recreate them.
CREATE TABLE RENTAL_PAYMENT (
    RENTAL_PAYMENT_ID BIGINT PRIMARY KEY,
    TENANT_ID BIGINT NOT NULL REFERENCES TENANT (TENANT_ID),
    RENTED_OBJECT_ID BIGINT NOT NULL REFERENCES RENTED_OBJECT (RENTED_OBJECT_ID),
    AMOUNT NUMERIC(14,2) NOT NULL CHECK (AMOUNT > 0),
    PAYMENT_DATE DATE NOT NULL,
    DESCRIPTION VARCHAR(500),
    REQUEST_ID UUID NOT NULL,
    REQUEST_PAYLOAD TEXT NOT NULL,
    DELETED BOOLEAN NOT NULL DEFAULT FALSE,
    VERSION BIGINT NOT NULL DEFAULT 0,
    INSERT_DATE TIMESTAMP NOT NULL,
    UPDATE_DATE TIMESTAMP,
    INSERT_OPERATOR VARCHAR(60) NOT NULL,
    UPDATE_OPERATOR VARCHAR(60),
    CONSTRAINT UK_RENTAL_PAYMENT_REQUEST UNIQUE (TENANT_ID, REQUEST_ID)
);
CREATE INDEX I_RENTAL_PAYMENT_TENANCY ON RENTAL_PAYMENT (TENANT_ID, RENTED_OBJECT_ID, PAYMENT_DATE);
CREATE INDEX I_SETTLEMENT_TENANCY ON SETTLEMENT (TENANT_ID, RENTED_OBJECT_ID);

-- Opening coverage is technical data, not money received on the migration date.
-- Preserve the original coverage on edits; remove it with a deleted settlement.
CREATE TABLE SETTLEMENT_OPENING_CREDIT (
    SETTLEMENT_ID BIGINT PRIMARY KEY REFERENCES SETTLEMENT (SETTLEMENT_ID) ON DELETE CASCADE,
    AMOUNT NUMERIC(19,2) NOT NULL
);

INSERT INTO SETTLEMENT_OPENING_CREDIT (SETTLEMENT_ID, AMOUNT)
SELECT SETTLEMENT_ID, COALESCE(TOTAL_AMOUNT, 0) FROM SETTLEMENT
ON CONFLICT (SETTLEMENT_ID) DO NOTHING;

-- No runAlways/runOnChange: future settlements must never receive opening credit.
