-- Deposit may be requested manually in several instalments. Existing bills stay unchanged.
DROP INDEX uk_settlement_deposit_assessment;
CREATE SEQUENCE SETTLEMENT_CHARGE_SEQ START WITH 1 INCREMENT BY 1;
CREATE TABLE SETTLEMENT_CHARGE (
    SETTLEMENT_CHARGE_ID BIGINT PRIMARY KEY,
    SETTLEMENT_ID BIGINT NOT NULL REFERENCES SETTLEMENT(SETTLEMENT_ID) ON DELETE CASCADE,
    POSITION INTEGER NOT NULL,
    TYPE VARCHAR(20) NOT NULL CHECK (TYPE IN ('DEPOSIT', 'OTHER')),
    AMOUNT NUMERIC(14,2) NOT NULL CHECK (AMOUNT > 0),
    DESCRIPTION VARCHAR(500),
    CONSTRAINT UK_SETTLEMENT_CHARGE_POSITION UNIQUE (SETTLEMENT_ID, POSITION)
);
INSERT INTO SETTLEMENT_CHARGE(SETTLEMENT_CHARGE_ID, SETTLEMENT_ID, POSITION, TYPE, AMOUNT, DESCRIPTION)
SELECT nextval('SETTLEMENT_CHARGE_SEQ'), SETTLEMENT_ID, 0, 'DEPOSIT', DEPOSIT_TOP_UP, 'Kaucja'
FROM SETTLEMENT WHERE DEPOSIT_TOP_UP > 0;
INSERT INTO SETTLEMENT_CHARGE(SETTLEMENT_CHARGE_ID, SETTLEMENT_ID, POSITION, TYPE, AMOUNT, DESCRIPTION)
SELECT nextval('SETTLEMENT_CHARGE_SEQ'), SETTLEMENT_ID, CASE WHEN DEPOSIT_TOP_UP > 0 THEN 1 ELSE 0 END, 'OTHER', ADDITIONAL_CHARGE, ADDITIONAL_CHARGE_DESCRIPTION
FROM SETTLEMENT WHERE ADDITIONAL_CHARGE > 0;
